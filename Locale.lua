function BB:ApplyLanguage()
  local pref = BananaBankDB and BananaBankDB.lang or "auto"
  if pref == "deDE" or pref == "enUS" then
    self.lang = pref
  elseif GetLocale() == "deDE" then
    self.lang = "deDE"
  else
    self.lang = "enUS"
  end
end

function BB.T(key)
  local t = BB.L[BB.lang or "enUS"]
  return (t and t[key]) or BB.L.enUS[key] or key
end
